import { test, expect, type Page } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { pdfFixture } from "../fixtures/pdf";
import { testAccounts, testPassword } from "./accounts";

async function login(page: Page, role: keyof typeof testAccounts) {
  await page.goto("/admin/login");
  await page.getByLabel("Email pengelola").fill(testAccounts[role].email);
  await page.getByLabel("Sandi", { exact: true }).fill(testPassword);
  await page.getByRole("button", { name: "Masuk ke CMS", exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/, { timeout: 15000 });
}
test("sumber PDF diekstrak per halaman, diperiksa dan disetujui tanpa membuka file ke publik", async ({ page, browser, baseURL, isMobile }) => {
  test.setTimeout(120000);
  await page.setViewportSize({ width: isMobile ? 320 : 1440, height: 900 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  const approver = await browser.newContext({ baseURL, viewport: page.viewportSize()! }), visitor = await browser.newContext({ baseURL });
  try {
    await login(page, "editor"); await page.goto("/admin/dokumen/baru");
    const title = `Sumber PDF ${randomUUID().slice(0, 8)}`, slug = `pdf-${randomUUID()}`;
    await expect(page.getByRole("textbox", { name: "Judul", exact: true })).toBeEnabled();
    await page.getByRole("textbox", { name: "Judul", exact: true }).fill(title);
    await page.getByLabel("Slug").fill(slug);
    await page.getByRole("textbox", { name: "Ringkasan", exact: true }).fill("Sumber sintetis untuk pemeriksaan PDF privat.");
    await page.getByLabel("Tanggal tinjauan materi", { exact: true }).fill("2026-10-21");
    await page.getByRole("textbox", { name: "Nomor peraturan", exact: true }).fill("UJI 1");
    await page.getByRole("textbox", { name: "Tahun", exact: true }).fill("2026");
    await page.getByRole("textbox", { name: "Penerbit", exact: true }).fill("Instansi sintetis");
    await page.getByRole("textbox", { name: "URL dokumen resmi (.go.id)", exact: true }).fill("https://www.djkn.kemenkeu.go.id/");
    await page.getByRole("textbox", { name: "Catatan status & riwayat", exact: true }).fill("Berlaku pada fixture. Tidak ada aturan perubahan terkait.");
    await page.getByRole("combobox", { name: "Status peraturan terverifikasi", exact: true }).selectOption("current");
    await page.getByRole("checkbox", { name: "Penilai Pemerintah", exact: true }).check();
    await page.getByRole("button", { name: "Tambah sumber", exact: true }).click();
    await page.getByLabel("Judul sumber", { exact: true }).fill("Rujukan fixture PDF");
    await page.getByLabel("URL HTTPS publik", { exact: true }).fill("https://www.djkn.kemenkeu.go.id/");
    await page.getByLabel("Tanggal tinjauan sumber", { exact: true }).fill("2026-10-21");
    const upload = page.getByLabel("Unggah PDF", { exact: true });
    const send = async (buffer: Buffer) => {
      const [response] = await Promise.all([page.waitForResponse(response => new URL(response.url()).pathname === "/api/documents" && response.request().method() === "POST"), upload.setInputFiles({ name: "fixture.pdf", mimeType: "application/pdf", buffer })]);
      return response;
    };
    expect((await send(Buffer.from("PDF palsu"))).status()).toBe(400);
    await expect(page.getByRole("main").getByRole("alert")).toHaveText("Berkas tidak dapat dibaca sebagai PDF yang sah.");
    await expect(upload).toBeFocused(); await expect(page.getByRole("textbox", { name: "Judul", exact: true })).toHaveValue(title);
    expect((await send(pdfFixture([""]))).status()).toBe(201);
    await expect(page.getByText(/Ada halaman tanpa teks yang memadai/)).toBeVisible();
    const reviewed = page.getByRole("checkbox", { name: /Saya telah mencocokkan seluruh halaman/ });
    await reviewed.check(); await page.getByRole("button", { name: "Simpan draf", exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/dokumen\/[a-f0-9-]{36}$/, { timeout: 15000 });
    const contentUrl = page.url();
    await expect(page.getByRole("status").filter({ hasText: "Draf berhasil disimpan" })).toBeVisible();
    await page.getByRole("button", { name: "Ajukan pemeriksaan", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: /Selesaikan OCR/ })).toBeVisible();
    const lines = ["Pasal 1. Halaman pertama sumber PDF sintetis untuk pemeriksaan.", "Pasal 2. Halaman kedua dengan lampiran sintetis yang ditinjau."];
    const uploaded = await send(pdfFixture(lines)); expect(uploaded.status()).toBe(201);
    const { id } = await uploaded.json();
    await expect(reviewed).not.toBeChecked();
    const preview = page.getByRole("group", { name: "Lampiran PDF privat", exact: true });
    await expect(preview.getByRole("region", { name: "Teks halaman PDF 1", exact: true })).toHaveText(lines[0]);
    await preview.getByRole("button", { name: "Halaman berikutnya", exact: true }).click();
    await expect(preview.getByRole("region", { name: "Teks halaman PDF 2", exact: true })).toHaveText(lines[1]);
    await expect(preview.getByRole("region", { name: "Teks halaman PDF 2", exact: true })).toBeFocused();
    await page.getByRole("button", { name: "Simpan draf", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "Draf berhasil disimpan" })).toBeVisible();
    await page.getByRole("button", { name: "Ajukan pemeriksaan", exact: true }).click();
    await expect(reviewed).toBeFocused(); await expect(reviewed).toHaveAttribute("aria-invalid", "true");
    await reviewed.check(); await page.getByRole("button", { name: "Simpan draf", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "Draf berhasil disimpan" })).toBeVisible();
    await preview.screenshot({ path: test.info().outputPath("pdf-editor.png") });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    await page.getByRole("button", { name: "Ajukan pemeriksaan", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "Revisi diajukan" })).toBeVisible();
    const reviewer = await approver.newPage(); await reviewer.emulateMedia({ reducedMotion: "reduce" }); await login(reviewer, "approver"); await reviewer.goto(contentUrl);
    await expect(reviewer.getByRole("region", { name: "Teks halaman PDF 1", exact: true })).toHaveText(lines[0]);
    expect((await approver.request.get(`/api/documents/${id}/file`)).status()).toBe(200);
    await reviewer.getByRole("button", { name: "Setujui sumber PDF", exact: true }).click();
    await expect(reviewer.getByRole("status").filter({ hasText: "Sumber disetujui untuk tahap indeks" })).toBeVisible();
    await reviewer.getByRole("status").filter({ hasText: "Sumber disetujui untuk tahap indeks" }).scrollIntoViewIfNeeded();
    await expect(reviewer.getByRole("status").filter({ hasText: "Sumber disetujui untuk tahap indeks" })).toBeInViewport({ ratio: 1 });
    await reviewer.screenshot({ path: test.info().outputPath("pdf-disetujui.png") });
    for (const path of [`/api/documents/${id}`, `/api/documents/${id}/file`]) expect((await visitor.request.get(path)).status()).toBe(404);
    expect((await (await visitor.request.get("/sitemap.xml")).text()).includes(slug)).toBe(false);
    const search = await visitor.newPage(); await search.goto(`/pencarian?q=${slug}`);
    await expect(search.getByRole("combobox", { name: "Jenis konten", exact: true }).locator('option[value="knowledge"]')).toHaveCount(0);
    await page.goto(contentUrl); await page.getByRole("textbox", { name: "Judul", exact: true }).fill(`${title} revisi baru`);
    await page.getByRole("button", { name: "Simpan draf", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "Draf berhasil disimpan" })).toBeVisible();
    await expect(page.getByRole("region", { name: "Sumber disetujui: revisi 1", exact: true }).getByRole("heading", { name: title, exact: true })).toBeVisible();
    await reviewer.goto(contentUrl); await reviewer.getByText("Tarik sumber dari korpus", { exact: true }).click();
    await reviewer.getByLabel("Alasan penarikan", { exact: true }).fill("Tinjauan ulang fixture sumber PDF.");
    await reviewer.getByRole("button", { name: "Tarik sumber PDF", exact: true }).click();
    await expect(reviewer.getByRole("status").filter({ hasText: "Sumber ditarik dari korpus" })).toBeVisible();
    expect((await visitor.request.get(`/api/documents/${id}/file`)).status()).toBe(404);
    expect((await approver.request.get(`/api/documents/${id}/file`)).status()).toBe(200);
  } finally { await approver.close(); await visitor.close(); }
});
